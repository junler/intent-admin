-- +goose Up
-- The demo table exists to exercise the Capability layer end to end before any
-- business module is written: list, update, delete, preview, undo, export.
-- Phase 1 adds the real schema (plan §9); this table and its capabilities can
-- be deleted once the system modules land.
CREATE TABLE IF NOT EXISTS demo_item (
    item_id     int          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    category    varchar(32)  NOT NULL DEFAULT 'default',
    amount      bigint       NOT NULL DEFAULT 0,          -- integer cents
    status      char(1)      NOT NULL DEFAULT '0',        -- 0 正常 / 1 停用
    del_flag    char(1)      NOT NULL DEFAULT '0',        -- 0 存在 / 2 删除
    remark      varchar(500),
    create_by   varchar(64)  NOT NULL DEFAULT '',
    create_time timestamptz  NOT NULL DEFAULT now(),
    update_by   varchar(64)  NOT NULL DEFAULT '',
    update_time timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_demo_item_status ON demo_item (status, del_flag);
CREATE INDEX IF NOT EXISTS idx_demo_item_create_time ON demo_item (create_time DESC);

