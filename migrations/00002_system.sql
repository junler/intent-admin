CREATE TABLE sys_user (
    user_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name varchar(30) NOT NULL,
    nick_name varchar(30) NOT NULL,
    user_type varchar(2) NOT NULL DEFAULT '00',
    email varchar(50) NOT NULL DEFAULT '',
    phonenumber varchar(20) NOT NULL DEFAULT '',
    sex char(1) NOT NULL DEFAULT '0',
    password varchar(200) NOT NULL,
    avatar varchar(255) NOT NULL DEFAULT '',
    status char(1) NOT NULL DEFAULT '0',
    del_flag char(1) NOT NULL DEFAULT '0',
    login_ip varchar(128) NOT NULL DEFAULT '',
    login_date timestamptz,
    ai_max_risk varchar(10) CHECK (ai_max_risk IN ('low', 'medium', 'high', 'critical')),
    create_by varchar(64) NOT NULL DEFAULT '',
    create_time timestamptz NOT NULL DEFAULT now(),
    update_by varchar(64) NOT NULL DEFAULT '',
    update_time timestamptz NOT NULL DEFAULT now(),
    remark varchar(500) DEFAULT ''
);

CREATE UNIQUE INDEX idx_sys_user_name_alive ON sys_user (user_name) WHERE del_flag = '0';
CREATE INDEX idx_sys_user_status ON sys_user (status, del_flag);

