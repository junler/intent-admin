import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
const root = resolve('src/pages');
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) result.push(...await walk(path));
    else if (entry.name.endsWith('.tsx') && !entry.name.includes('.test.')) result.push(path);
  }
  return result;
}
const names = (await walk(root)).map((p) => relative(root, p).replaceAll('\\', '/').replace(/\.tsx$/, '')).filter((p) => !p.startsWith('dynamic/') && !p.startsWith('login/')).sort();
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/pageRegistry.ts', '// Generated by scripts/generate-pages.mjs. Backend component strings resolve only bundled pages.\nexport const pageRegistry = {\n' + names.map((p) => `  '${p}': () => import('@/pages/${p}'),`).join('\n') + '\n};\n');
